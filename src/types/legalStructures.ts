export type TaxRegime = 
  | 'micro_bic'              // Micro-BIC (artisans/commerçants)
  | 'micro_bnc'              // Micro-BNC (professions libérales)
  | 'reel_simplifie'         // Réel simplifié
  | 'reel_normal'            // Réel normal
  | 'is'                     // Impôt sur les sociétés
  | 'ir_option'              // IR sur option
  | 'exonere';               // Exonéré (associations, etc.)

export type SocialRegime = 
  | 'tns'                    // Travailleur Non Salarié
  | 'tns_pamc'               // TNS + PAMC (médecins)
  | 'assimile_salarie'       // Assimilé salarié
  | 'regime_general'         // Régime général
  | 'non_applicable';        // Non applicable

export type TVARegime = 
  | 'franchise'              // Franchise en base (exo TVA)
  | 'reel_simplifie'         // Réel simplifié
  | 'reel_normal'            // Réel normal
  | 'exonere';               // Exonéré

export interface LegalStructure {
  id: LegalStructureType;
  name: string;
  fullName: string;
  description: string;
  category: 'individual' | 'commercial' | 'civil' | 'social' | 'special';
  
  // Capital requirements
  capitalMin: number;
  capitalMax: number | null;
  capitalRecommended: number;
  capitalLocked: boolean;
  
  // Associates
  associatesMin: number;
  associatesMax: number | null;
  
  // Employee limits
  employeesMax: number | null;
  
  // Revenue thresholds
  revenueThresholds: {
    micro?: number;          // Threshold for micro regime
    simplified?: number;     // Threshold for simplified regime
    max?: number;            // Max revenue allowed
  };
  
  // Tax configuration
  taxRegime: TaxRegime;
  taxRegimeOptions: TaxRegime[];
  corporateTaxRate: number;
  dividendTaxRate: number;
  
  // Social charges
  socialRegime: SocialRegime;
  socialChargesRate: number;
  socialChargesMin: number;
  
  // TVA
  tvaRegime: TVARegime;
  tvaThreshold: number;
  
  // Governance
  governanceComplexity: 1 | 2 | 3 | 4 | 5;
  requiresStatutes: boolean;
  requiresCommissaire: boolean;
  requiresCAC: boolean;
  requiresBoard: boolean;
  
  // Registration & costs
  registrationCost: number;
  annualCost: number;
  
  // Credibility & image
  credibilityBonus: number;
  institutionalImage: number;
  
  // Flexibility
  flexibilityScore: number;
  canRaiseFunds: boolean;
  canGoPublic: boolean;
  canExport: boolean;
  canHireAbroad: boolean;
  
  // Liability
  limitedLiability: boolean;
  personalGuaranteeRequired: boolean;
  
  // Specific obligations
  obligations: string[];
  advantages: string[];
  disadvantages: string[];
}

