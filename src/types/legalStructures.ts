// Helper functions
export function getLegalStructure(id: LegalStructureType): LegalStructure {
  return LEGAL_STRUCTURES[id];
}

export function getLegalStructuresByCategory(category: LegalStructure['category']): LegalStructure[] {
  return Object.values(LEGAL_STRUCTURES).filter(s => s.category === category);
}

export function calculateRegistrationCosts(structure: LegalStructure, capital: number): number {
  let baseCost = structure.registrationCost;
  
  // Greffe fees based on capital
  if (capital > 225000) baseCost += 500;
  else if (capital > 100000) baseCost += 300;
  else if (capital > 50000) baseCost += 200;
  
  // Annonce légale
  baseCost += 150;
  
  return baseCost;
}

export function calculateAnnualObligations(structure: LegalStructure, revenue: number, employees: number): number {
  let cost = structure.annualCost;
  
  // CAC if required
  if (structure.requiresCAC) {
    cost += 3000;
    if (revenue > 1000000) cost += 2000;
    if (revenue > 5000000) cost += 5000;
  }
  
  // Dépôt des comptes
  if (structure.requiresCommissaire) {
    cost += 500;
  }
  
  // CSE if 11+ employees
  if (employees >= 11) {
    cost += employees * 50;
  }
  
  return cost;
}
